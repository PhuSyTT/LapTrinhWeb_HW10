package vn.iotstar;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.test.context.TestPropertySource;
import vn.iotstar.entity.User;
import vn.iotstar.services.JwtService;

import java.util.Date;
import java.util.HashMap;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@TestPropertySource(properties = {
        "security.jwt.secret-key=3cfa76ef14937c1c0ea519f8fc057a80fcd04a7420f8e8bcd0a7567c272e007b",
        "security.jwt.expiration-time=3600000"
})
public class JwtServiceTest {

    @Autowired
    private JwtService jwtService;

    private UserDetails userDetails;

    @BeforeEach
    void setUp() {
        User user = new User();
        user.setEmail("trungnh@hcmute.edu.vn");
        user.setFullName("Nguyen Huu Trung");
        user.setPassword("password123");
        userDetails = user;
    }

    @Test
    void testGenerateTokenWithNimbus() {
        String token = jwtService.generateToken(userDetails);
        assertNotNull(token);
        // JWT must consist of 3 parts separated by dots
        String[] parts = token.split("\\.");
        assertEquals(3, parts.length, "Nimbus JWT must have 3 parts: Header, Payload, Signature");
    }

    @Test
    void testExtractUsernameWithNimbus() {
        String token = jwtService.generateToken(userDetails);
        String username = jwtService.extractUsername(token);
        assertEquals(userDetails.getUsername(), username);
    }

    @Test
    void testIsTokenValidWithNimbus() {
        String token = jwtService.generateToken(userDetails);
        boolean isValid = jwtService.isTokenValid(token, userDetails);
        assertTrue(isValid, "Token generated by Nimbus should be valid for user");
    }

    @Test
    void testGenerateTokenWithCustomClaims() {
        Map<String, Object> claims = new HashMap<>();
        claims.put("role", "ROLE_ADMIN");
        claims.put("userId", 100);

        String token = jwtService.generateToken(claims, userDetails);
        assertNotNull(token);

        String username = jwtService.extractUsername(token);
        assertEquals("trungnh@hcmute.edu.vn", username);

        Object role = jwtService.extractClaim(token, c -> c.getClaim("role"));
        assertEquals("ROLE_ADMIN", role);
    }

    @Test
    void testTokenExpirationTime() {
        long expiration = jwtService.getExpirationTime();
        assertEquals(3600000L, expiration);
    }
}
